function ConvertTo-CIPPSignInExplanationNote {
    <#
    .SYNOPSIS
        Renders a sign-in explanation bundle (Get-CIPPSignInExplanation) as a ConnectWise note / copyable summary.
    .DESCRIPTION
        Same Markdown rules as the mail triage note (ConvertTo-CIPPMailTriageNote): only **bold**, *italic*, links
        and "1." lists, which render in both the classic Manage UI and Asio; no HTML, no headings, no "-" bullets.
        Capped at MaxLength (Asio's note limit is 12000): per-sign-in details are dropped first, then sign-ins.
        Also used as the page's "Copy summary" text. Aspendora fork addition (Vikunja CIPP-10).
    .FUNCTIONALITY
        Internal
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]$Bundle,
        [int]$MaxLength = 12000,
        [int]$SignInRows = 5
    )

    $Clean = { param($Text) (([string]$Text) -replace '<[^>]+>', '' -replace '[\r\n]+', ' ').Trim() }
    $Render = {
        param([int]$Rows, [bool]$WithDetails)
        $Lines = [System.Collections.Generic.List[string]]::new()
        $Lines.Add('**Sign-in failure explanation (CIPP)**')
        $Lines.Add('')
        $Lines.Add("Tenant: $($Bundle.Tenant)  ")
        $Lines.Add("User: $(if ($Bundle.UserPrincipalName) { $Bundle.UserPrincipalName } else { '(from correlation ID)' })  ")
        if ($Bundle.CorrelationId) { $Lines.Add("Correlation / request ID: $($Bundle.CorrelationId)  ") }
        $Lines.Add("Window: $($Bundle.WindowStart.Display) to $($Bundle.WindowEnd.Display)$(if (-not $Bundle.CorrelationId) { " (last $($Bundle.Hours) h)" })$(if ($Bundle.IncludeNonInteractive) { ', interactive and non-interactive' } else { ', interactive sign-ins' })  ")
        $Lines.Add("Run at: $($Bundle.GeneratedAt.Display). Times are US Central with UTC in brackets.")
        $Lines.Add('')
        if ($Bundle.User) {
            $U = $Bundle.User
            $Lines.Add("Account: $(if ($U.AccountEnabled -eq $false) { '**disabled**' } else { 'enabled' }); per-user MFA: $(if ($U.PerUserMfaState) { $U.PerUserMfaState } else { 'unknown' }); security defaults: $(if ($Bundle.SecurityDefaultsEnabled -eq $true) { 'on' } elseif ($Bundle.SecurityDefaultsEnabled -eq $false) { 'off' } else { 'unknown' })$(if ($U.Synced) { '; synced from on-premises AD' }).")
            $Lines.Add('')
        }
        $Lines.Add("**Diagnosis:** $(& $Clean $Bundle.Headline)")
        $Lines.Add('')
        if ($Bundle.LicenseRequired) {
            $Lines.Add('Read-only; nothing was changed. Generated by the CIPP sign-in failure explainer.')
            return ($Lines -join "`n")
        }
        $C = $Bundle.Counts
        if ($C) { $Lines.Add("Sign-ins in window: $($C.Total) ($($C.Failures) failed, $($C.Interrupts) interrupted, $($C.Successes) succeeded)$(if ($Bundle.LatestSuccess) { "; latest success $($Bundle.LatestSuccess)" }).$(if ($Bundle.Truncated) { ' Only the newest 999 were read.' })") }
        if ($Bundle.PasswordAttempts) { $Lines.Add("Password attempts: $(& $Clean $Bundle.PasswordAttempts.Summary)") }
        $Lines.Add('')

        $N = 0
        foreach ($S in @($Bundle.SignIns | Where-Object { $_ -and $_.Outcome -ne 'Success' } | Select-Object -First $Rows)) {
            $N++
            $Code = if ($S.ErrorCode) { " AADSTS$($S.ErrorCode)" } else { '' }
            $Resolved = if ($S.ResolvedLater) { ' *(followed by a successful sign-in)*' } else { '' }
            $Lines.Add("$N. **$($S.Time) - $(& $Clean $S.Title)**$Code - $($S.App)$(if ($S.ClientApp) { " via $($S.ClientApp)" }), $(if ($S.Location) { $S.Location } else { 'unknown location' })$(if ($S.IPAddress) { " ($($S.IPAddress))" })$Resolved")
            if ($WithDetails) {
                $Lines.Add("    *Why:* $(& $Clean $S.Explanation)")
                foreach ($D in @($S.Details)) { if ($D) { $Lines.Add("    $(& $Clean $D)") } }
                if ($S.Fix) { $Lines.Add("    *Fix:* $(& $Clean $S.Fix)") }
                if ($S.CorrelationId) { $Lines.Add("    Correlation ID: $($S.CorrelationId) | Request ID: $($S.RequestId)") }
            }
        }
        if ($N -eq 0) { $Lines.Add('No failed or interrupted sign-ins in this window.') }
        $Lines.Add('')
        $First = @($Bundle.SignIns | Where-Object { $_ -and $_.Links.EntraUserSignIns }) | Select-Object -First 1
        if ($First) { $Lines.Add("[Entra sign-in log for this user]($($First.Links.EntraUserSignIns))  ") }
        $Lines.Add('For the full Microsoft analysis: Entra admin center > Diagnose and solve problems > Sign-in diagnostic, with the correlation ID above.')
        $Lines.Add('')
        $Lines.Add('Read-only; nothing was changed. Generated by the CIPP sign-in failure explainer.')
        $Lines -join "`n"
    }

    $Text = & $Render $SignInRows $true
    if ($Text.Length -gt $MaxLength) { $Text = & $Render $SignInRows $false }
    if ($Text.Length -gt $MaxLength) { $Text = & $Render 2 $true }
    if ($Text.Length -gt $MaxLength) { $Text = & $Render 1 $false }
    if ($Text.Length -gt $MaxLength) { $Text = $Text.Substring(0, $MaxLength - 20) + "`n...(truncated)" }
    $Text
}
