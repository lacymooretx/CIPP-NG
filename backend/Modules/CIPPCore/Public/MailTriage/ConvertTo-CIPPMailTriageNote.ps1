function ConvertTo-CIPPMailTriageNote {
    <#
    .SYNOPSIS
        Renders a mail triage bundle (Get-CIPPMailTriage) as a ConnectWise ticket note.
    .DESCRIPTION
        ConnectWise stores note text verbatim and renders Markdown; only **bold**, *italic*, links and "1." lists are
        safe in both the classic Manage UI and the Asio UI, so that is all this uses (no HTML, no headings, no "-"
        bullets), with a blank line after each list. Text is capped at MaxLength (Asio's note limit is 12000):
        evidence rows are dropped first, then findings.
        Aspendora fork addition (Vikunja CIPP-38).
    .FUNCTIONALITY
        Internal
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]$Bundle,
        [int]$MaxLength = 12000,
        [int]$EvidenceRows = 5
    )

    $Clean = { param($Text) (([string]$Text) -replace '<[^>]+>', '' -replace '[\r\n]+', ' ').Trim() }
    $Render = {
        param([int]$Rows, [bool]$WithFindings)
        $Lines = [System.Collections.Generic.List[string]]::new()
        $Lines.Add("**Mail delivery triage (CIPP)** - overall: **$($Bundle.Overall)**")
        $Lines.Add('')
        $Lines.Add("Tenant: $($Bundle.Tenant)  ")
        $Lines.Add("Recipient: $($Bundle.Recipient)  ")
        $Lines.Add("Sender: $(if ($Bundle.Sender) { $Bundle.Sender } else { '(any)' })  ")
        $Lines.Add("Window: $($Bundle.WindowStart.Display) to $($Bundle.WindowEnd.Display) (last $($Bundle.Hours) h)  ")
        $Lines.Add("Run at: $($Bundle.GeneratedAt.Display). Times are US Central with UTC in brackets.")
        $Lines.Add('')
        $Lines.Add("**Summary:** $(& $Clean $Bundle.Summary)")
        $Lines.Add('')
        $N = 0
        foreach ($Step in @($Bundle.Steps)) {
            $N++
            $Lines.Add("$N. **$($Step.Title): $($Step.Status)** - $(& $Clean $Step.Summary)")
            if ($WithFindings) {
                foreach ($F in @($Step.Findings)) { if ($F) { $Lines.Add("    *Note:* $(& $Clean $F)") } }
            }
            if ($Rows -gt 0 -and $Step.Evidence) {
                $Items = @($Step.Evidence)
                $Shown = if ($Items.Count -eq 1 -and $Items[0] -isnot [string]) { $Items } else { $Items | Select-Object -First $Rows }
                foreach ($Item in @($Shown)) {
                    $Pairs = foreach ($P in $Item.PSObject.Properties) {
                        $V = $P.Value
                        if ($null -eq $V -or "$V" -eq '' -or ($V -is [System.Collections.IEnumerable] -and $V -isnot [string] -and @($V).Count -eq 0)) { continue }
                        if ($V -is [System.Collections.IEnumerable] -and $V -isnot [string]) {
                            $V = (@($V) | ForEach-Object { if ($_ -is [string]) { $_ } elseif ($_.PSObject.Properties['Value']) { $_.Value } else { ($_.PSObject.Properties | ForEach-Object { "$($_.Name)=$($_.Value)" }) -join ' ' } }) -join '; '
                        }
                        "$($P.Name): $(& $Clean $V)"
                    }
                    if ($Pairs) { $Lines.Add("    $(@($Pairs) -join ' | ')") }
                }
                if ($Items.Count -gt $Rows -and -not ($Items.Count -eq 1)) { $Lines.Add("    ...and $($Items.Count - $Rows) more in CIPP.") }
            }
        }
        $Lines.Add('')
        $Lines.Add('Read-only checks; nothing was changed. Generated by CIPP mail triage.')
        $Lines -join "`n"
    }

    $Text = & $Render $EvidenceRows $true
    if ($Text.Length -gt $MaxLength) { $Text = & $Render 1 $true }
    if ($Text.Length -gt $MaxLength) { $Text = & $Render 0 $true }
    if ($Text.Length -gt $MaxLength) { $Text = & $Render 0 $false }
    if ($Text.Length -gt $MaxLength) { $Text = $Text.Substring(0, $MaxLength - 20) + "`n...(truncated)" }
    $Text
}
